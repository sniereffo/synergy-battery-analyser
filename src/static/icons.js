// Build an <svg> for a Lucide icon. Only the vendored constant markup above is
// ever inserted as SVG markup.
function icon(name, { size = 16, cls = '' } = {}) {
    const inner = ICON_PATHS[name];
    if (!inner) return null;
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', size);
    svg.setAttribute('height', size);
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('class', ('icon ' + cls).trim());
    svg.innerHTML = inner;
    return svg;
}

// Replace <i data-icon="name" data-size="16"></i> placeholders in the page.
function hydrateIcons(root = document) {
    root.querySelectorAll('i[data-icon]').forEach(ph => {
        const svg = icon(ph.dataset.icon, { size: Number(ph.dataset.size) || 16, cls: ph.className });
        if (svg) ph.replaceWith(svg);
    });
}
